"""Puertos (Protocol). Los adaptadores los implementan; application solo depende de ellos."""
from datetime import datetime
from typing import Any, Protocol

from app.domain.entities import Cliente, MovimientoInventario, Producto, Usuario, Venta


class Transaccion(Protocol):
    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class CipherPort(Protocol):
    def cifrar(self, texto: str | None) -> str | None: ...
    def descifrar(self, token: str | None) -> str | None: ...


class ProductRepo(Protocol):
    def listar(self, q: str | None = None, categoria: str | None = None, solo_activos: bool = False,
               limit: int = 100, offset: int = 0) -> list[Producto]: ...
    def obtener(self, id: int) -> Producto | None: ...
    def obtener_por_sku(self, sku: str) -> Producto | None: ...
    def crear(self, producto: Producto) -> Producto: ...
    def actualizar(self, id: int, cambios: dict[str, Any]) -> Producto: ...
    def ajustar_stock(self, id: int, delta: int) -> bool: ...
    def categorias(self) -> list[str]: ...


class CustomerRepo(Protocol):
    def listar(self, q: str | None = None, limit: int = 100, offset: int = 0) -> list[Cliente]: ...
    def obtener(self, id: int) -> Cliente | None: ...
    def crear(self, cliente: Cliente) -> Cliente: ...
    def actualizar(self, id: int, cambios: dict[str, Any]) -> Cliente: ...
    def eliminar(self, id: int) -> None: ...
    def tiene_ventas(self, id: int) -> bool: ...


class SaleRepo(Protocol):
    def crear(self, venta: Venta) -> Venta: ...
    def obtener(self, id: int) -> Venta | None: ...
    def listar(self, desde: datetime | None = None, hasta: datetime | None = None,
               customer_id: int | None = None, limit: int = 50, offset: int = 0) -> list[Venta]: ...


class InventoryRepo(Protocol):
    def registrar(self, mov: MovimientoInventario) -> MovimientoInventario: ...
    def listar(self, product_id: int | None = None, tipo: str | None = None,
               limit: int = 100, offset: int = 0) -> list[MovimientoInventario]: ...


class KpiRepo(Protocol):
    def totales(self, desde: datetime, hasta: datetime) -> dict[str, float]: ...
    def serie_diaria(self, desde: datetime, hasta: datetime) -> list[dict[str, Any]]: ...
    def top_productos(self, desde: datetime, hasta: datetime, limit: int) -> list[dict[str, Any]]: ...
    def por_categoria(self, desde: datetime, hasta: datetime) -> list[dict[str, Any]]: ...
    def valor_inventario(self) -> float: ...
    def contar_bajo_stock(self, umbral: int) -> int: ...


class UserRepo(Protocol):
    def obtener_por_username(self, username: str) -> Usuario | None: ...
    def crear(self, usuario: Usuario) -> Usuario: ...


