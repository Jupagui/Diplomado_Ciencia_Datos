    def demanda(self, horizon: int, product_id: int | None = None) -> list[dict[str, Any]]: ...
    def reglas(self, limit: int = 100) -> list[dict[str, Any]]: ...
    def segmentos(self) -> list[dict[str, Any]]: ...


